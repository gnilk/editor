#!/usr/bin/env python3
"""
Generate gvt's character-width tables (src/WidthTables.inc) from Python's unicodedata. Stdlib only.

  tools/gen_width.py > src/WidthTables.inc

Rules (wcwidth-style, as xterm/libvterm/Ghostty without grapheme mode):
  width 2: East Asian Width W or F. Since Unicode 9 every Emoji_Presentation character is W, so emoji are covered.
           Plus the unassigned CJK planes (U+20000-2FFFD, U+30000-3FFFD), wide by default.
  width 0: combining marks (Mn, Me), format characters (Cf) except SOFT HYPHEN, Hangul medial/final jamo
           (U+1160-11FF), which join the previous cell.
  width 1: everything else.
The Unicode version is the one Python was built with; it is written into the output.
"""
import sys
import unicodedata


def ranges(predicate):
    out = []
    start = None
    for cp in range(0x110000):
        hit = predicate(cp)
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def is_wide(cp):
    if 0x20000 <= cp <= 0x2FFFD or 0x30000 <= cp <= 0x3FFFD:
        return True
    return unicodedata.east_asian_width(chr(cp)) in ('W', 'F')


def is_zero(cp):
    if cp == 0x00AD:
        return False
    if 0x1160 <= cp <= 0x11FF:
        return True
    return unicodedata.category(chr(cp)) in ('Mn', 'Me', 'Cf')


def emit(name, table):
    print(f'    // {len(table)} ranges')
    print(f'    constexpr CodepointRange {name}[] = {{')
    for first, last in table:
        print(f'        {{0x{first:05X}, 0x{last:05X}}},')
    print('    };')


def main():
    print('//')
    print(f'// GENERATED by tools/gen_width.py from Unicode {unicodedata.unidata_version} - do not edit.')
    print('//')
    emit('kWideRanges', ranges(is_wide))
    print()
    emit('kZeroWidthRanges', ranges(is_zero))
    return 0


if __name__ == '__main__':
    sys.exit(main())
