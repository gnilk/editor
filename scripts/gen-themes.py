#!/usr/bin/env python3
"""
Writes the shipped themes made from other editors' themes (docs/theme-collection.md 4.1): for each overlay in
Assets/ThemeSources/overlays/<file>.json, the editor's own importer converts the source it names (under
Assets/ThemeSources/) and the overlay is applied on top - our name, our extra colours. The result goes to
Assets/Resources/Themes/<file>.theme.yml + <file>.colors.json, which are committed.

    python3 scripts/gen-themes.py --exe <goatedit>           # write them
    python3 scripts/gen-themes.py --exe <goatedit> --check   # exit 1 if a committed theme isn't what this writes

Run it after the importer changes or a source/overlay is added. The importer runs in a sandbox HOME - never the user's.
Overlay keys: "source" (under Assets/ThemeSources/), "name" (the theme's name), "variables" (merged into the colour
file's variables), "colors" (merged into its sections, key by key), "font_styles" (merged, key by key). Keys starting with '_' are comments.
"""
import argparse
import json
import os
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCES = os.path.join(ROOT, 'Assets', 'ThemeSources')
OVERLAYS = os.path.join(SOURCES, 'overlays')
THEMES = os.path.join(ROOT, 'Assets', 'Resources', 'Themes')


class GenError(Exception):
    pass


def convert(exe, source, fileName):
    """The importer's theme.yml text and colours json for 'source', converted in a sandbox HOME"""
    with tempfile.TemporaryDirectory(prefix='goatedit-gen-themes-') as home:
        env = {'PATH': '/usr/bin:/bin', 'HOME': home, 'XDG_CONFIG_HOME': os.path.join(home, '.config'),
               'XDG_STATE_HOME': os.path.join(home, '.local', 'state'), 'LANG': 'C.UTF-8'}
        r = subprocess.run([exe, '--import-theme', source, '--name', fileName], env=env, cwd=ROOT,
                           capture_output=True, text=True)
        out = os.path.join(home, '.config', 'goatedit', 'themes')
        themePath = os.path.join(out, fileName + '.theme.yml')
        colorsPath = os.path.join(out, fileName + '.colors.json')
        if r.returncode != 0 or not os.path.exists(themePath) or not os.path.exists(colorsPath):
            raise GenError(f'importing {source} failed (exit {r.returncode}):\n{r.stdout}{r.stderr}')
        with open(themePath, encoding='utf-8') as f:
            themeText = f.read()
        with open(colorsPath, encoding='utf-8') as f:
            colors = json.load(f)
    return themeText, colors


def quoted(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"') + '"'


def apply_overlay(themeText, colors, overlay, overlayName, source):
    sourceRel = os.path.relpath(source, ROOT)
    setsAnsi = all(f'ansi{i}' in overlay.get('variables', {}) for i in range(16))
    lines = []
    for line in themeText.splitlines():
        if line.startswith('# Imported from '):
            lines.append(f'# Generated by scripts/gen-themes.py from {sourceRel} + Assets/ThemeSources/overlays/{overlayName}')
            lines.append('# - do not edit: change the overlay (or the importer) and run the script again.')
            continue
        if line.startswith('# Tune the colours in '):
            continue
        if setsAnsi and 'ANSI colours not in the theme' in line:
            lines.append('#   - terminal: the 16 ANSI colours are from the overlay')
            continue
        if 'name' in overlay and line.startswith('name: '):
            lines.append('name: ' + quoted(overlay['name']))
            continue
        lines.append(line)
    if 'name' in overlay:
        colors['name'] = overlay['name']
    colors.setdefault('variables', {}).update(overlay.get('variables', {}))
    for section, entries in overlay.get('colors', {}).items():
        colors.setdefault('colors', {}).setdefault(section, {}).update(entries)
    if 'font_styles' in overlay:
        colors.setdefault('font_styles', {}).update(overlay['font_styles'])
    return '\n'.join(lines) + '\n', json.dumps(colors, indent=2, ensure_ascii=False) + '\n'


def generate(exe):
    """{path: text} for every theme an overlay makes"""
    out = {}
    names = sorted(n for n in os.listdir(OVERLAYS) if n.endswith('.json'))
    if not names:
        raise GenError(f'no overlays in {OVERLAYS}')
    for overlayName in names:
        with open(os.path.join(OVERLAYS, overlayName), encoding='utf-8') as f:
            overlay = json.load(f)
        if 'source' not in overlay:
            raise GenError(f'{overlayName}: no "source"')
        fileName = overlayName[:-len('.json')]
        source = os.path.join(SOURCES, overlay['source'])
        if not os.path.exists(source):
            raise GenError(f'{overlayName}: source {source} is missing')
        themeText, colors = convert(exe, source, fileName)
        themeText, colorsText = apply_overlay(themeText, colors, overlay, overlayName, source)
        out[os.path.join(THEMES, fileName + '.theme.yml')] = themeText
        out[os.path.join(THEMES, fileName + '.colors.json')] = colorsText
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__.strip().splitlines()[0])
    parser.add_argument('--exe', required=True, help='the goatedit binary (its importer converts)')
    parser.add_argument('--check', action='store_true', help='compare with the committed themes, write nothing')
    args = parser.parse_args()
    try:
        files = generate(os.path.abspath(args.exe))
    except GenError as e:
        print(f'gen-themes: {e}', file=sys.stderr)
        return 2
    stale = []
    for path, text in files.items():
        try:
            with open(path, encoding='utf-8') as f:
                current = f.read()
        except FileNotFoundError:
            current = None
        if current == text:
            continue
        stale.append(os.path.relpath(path, ROOT))
        if not args.check:
            with open(path, 'w', encoding='utf-8') as f:
                f.write(text)
    if args.check:
        if stale:
            print('gen-themes: out of date - run python3 scripts/gen-themes.py --exe <goatedit>: ' + ', '.join(stale), file=sys.stderr)
            return 1
        print(f'gen-themes: {len(files) // 2} theme(s) up to date')
        return 0
    print(f'gen-themes: wrote {len(stale)} file(s)' + (': ' + ', '.join(stale) if stale else ' (all up to date)'))
    return 0


if __name__ == '__main__':
    sys.exit(main())
